require("dotenv").config();
const express = require("express");
const cors = require("cors");
const helmet = require("helmet");
const path = require("path");
const { apiLimiter } = require("./middleware/rateLimit");
const app = express();
app.use(helmet({contentSecurityPolicy:false}));
app.use(cors({origin: process.env.PUBLIC_ORIGIN || "http://localhost:3000"}));
app.use(express.json({limit:"100kb"}));
app.use(express.urlencoded({extended:false, limit:"20kb"}));
app.use("/api", apiLimiter);
app.use(express.static(path.join(__dirname,"public")));
app.use("/api/menu", require("./routes/menu"));
app.use("/api/cart", require("./routes/cart"));
app.use("/api/orders", require("./routes/orders"));
app.use("/api/coupons", require("./routes/coupons"));
app.use("/api/cake-requests", require("./routes/cakeRequests"));
app.use("/api/reservations", require("./routes/reservations"));
app.use("/api/ai", require("./routes/ai"));
app.use("/api/admin", require("./routes/admin"));
app.get("/api/health", (_req,res)=>res.json({ok:true, business:process.env.BUSINESS_NAME || "Sweet Crust"}));
app.get("/", (_req,res)=>res.sendFile(path.join(__dirname,"public","index.html")));
app.use((req,res)=>res.status(404).json({error:"Not found"}));
app.use((err,req,res,next)=>{ console.error(err); res.status(err.status||500).json({error:process.env.NODE_ENV==="production"?"Something went wrong":err.message||"Server error"}); });
const port=Number(process.env.PORT)||3000;
app.listen(port,()=>console.log(`Sweet Crust running at http://localhost:${port}`));
